import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const array = (items) => `{${items.join(", ")}}`;
const url = (relative) => new URL(relative, import.meta.url);
const fromJson = (relative) => JSON.parse(readFileSync(url(`../reference/browser/src/data/${relative}`), "utf8"));
const server = await createServer({
  root: fileURLToPath(url("..")),
  configFile: false,
  server: { middlewareMode: true, hmr: false, watch: null },
  appType: "custom",
  logLevel: "silent",
});
let botTuning;
try {
  botTuning = await server.ssrLoadModule("/reference/browser/src/bots/BotConfig.ts");
} finally {
  await server.close();
}
const { applyDifficultyLevel, BOT_DIFFICULTIES } = botTuning;
const keys = [
  "reactionTimeMs", "aimErrorDegrees", "aimSettleSpeed", "burstLength", "burstCooldown", "aggression",
  "coverPreference", "flankChance", "weaponSwitchSkill", "reloadDiscipline", "visionRange", "hearingRange",
  "sightMinExposure", "damageScale", "healthScale", "spreadScale", "onTargetDegrees", "holdTime", "plantFeet",
];
const literal = (value) => Array.isArray(value) ? array(value.map(literal)) : String(value);
const decks = [0, 0.1].map((edge) => {
  const entries = Array.from({ length: 10 }, (_, index) => {
    const config = { ...BOT_DIFFICULTIES.regular };
    applyDifficultyLevel(config, index + 1, edge);
    return `        ${array(keys.map((key) => literal(config[key])))},`;
  });
  return `    {\n${entries.join("\n")}\n    },`;
});

const ids = ["mp44", "m40a3", "usp45"];
const weapons = ids.map((id) => {
  const config = fromJson(`weapons/${id}_style.json`);
  return array([
    config.magSize, config.maxReserveAmmo, config.damage, config.fireInterval,
    config.boltCycleDuration, config.adsSpread,
    ...[config.recoilHip, config.recoilAds].map((r) => array([r.pitch, r.yaw, r.kickBack])),
  ]);
});
const ads = ids.map((id) => {
  const { frames } = fromJson(`animations/${id}_ads_frames.json`);
  const entries = frames.map((f) => `    ${array([
    literal(f.position), literal(f.rotation), f.fov, f.scopeOpacity, f.sensitivityMultiplier,
  ])},`);
  return `constexpr AimFrame ${id}Aim[] = {\n${entries.join("\n")}\n};`;
});
const header = `// Generated by tools/generate-game-data.mjs from the browser's aim, weapon and difficulty data.
#pragma once

namespace fod::game_data {

struct Recoil { double pitch, yaw, kick; };
struct WeaponTuning {
    int mag, reserve, damage;
    double interval, cycle, spread;
    Recoil hip, ads;
};
struct AimFrame {
    double position[3], rotation[3];
    double fov, scope, sensitivity;
};
struct Difficulty {
    double reactionMs, aimError, aimSpeed, burst[2], burstCooldown[2], aggression;
    double cover, flank, switchSkill, reloadSkill, vision, hearing, exposure;
    double damage, health, spread, onTarget, hold[2];
    bool plantFeet;
};

constexpr WeaponTuning weapons[] = {
    ${weapons.join(",\n    ")},
};
${ads.join("\n")}
constexpr const AimFrame* aim[] = {mp44Aim, m40a3Aim, usp45Aim};
constexpr int aimLast[] = {
    sizeof(mp44Aim) / sizeof(AimFrame) - 1,
    sizeof(m40a3Aim) / sizeof(AimFrame) - 1,
    sizeof(usp45Aim) / sizeof(AimFrame) - 1,
};

constexpr Difficulty levels[2][10] = {
${decks.join("\n")}
};

} // namespace fod::game_data
`;
const output = url("../game_data.hpp");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== header) throw new Error("Run node tools/generate-game-data.mjs");
} else {
  writeFileSync(output, header);
}
